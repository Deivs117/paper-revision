"""Entry point: regenerates every simulation-derived figure covered by Tarea 1.

Accepts any simulation root that follows the existing family_dir/test_NNN layout — not hardcoded
to experiments/simulation/, so a freshly re-run batch (versioned in a new sibling directory per the
author's D-12 decision, see this experiment's README.md) can be regenerated by pointing
--simulation-root at it, with no code changes.
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "builders"))

from builders import macro_robustness, ecdf_phase_space  # noqa: E402


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--simulation-root", default="experiments/simulation",
                    help="Path to a family_dir/test_NNN[_VERDICT]/*.csv|json tree")
    p.add_argument("--output-dir", default="experiments/N-01-simulation-figure-regeneration/output")
    args = p.parse_args()

    os.makedirs(args.output_dir, exist_ok=True)

    grid_path = os.path.join(args.output_dir, "fig1_noise_robustness_grid.png")
    table_path = os.path.join(args.output_dir, "tab_consolidated_simulation_metrics.csv")
    data = macro_robustness.build_grid(args.simulation_root, grid_path)
    table = macro_robustness.build_consolidated_table(args.simulation_root)
    table.to_csv(table_path, index=False)
    print(f"[macro_robustness] wrote {grid_path}")
    print(f"[macro_robustness] wrote {table_path}")
    print(table.to_string(index=False))

    ecdf_phase_space.build_fig_a(args.simulation_root, os.path.join(args.output_dir, "FigA_Stability_Profile.png"))
    ecdf_phase_space.build_fig_b(args.simulation_root, os.path.join(args.output_dir, "FigB_Decision_Delay.png"))
    ecdf_phase_space.build_fig_c(args.simulation_root, os.path.join(args.output_dir, "FigC_Terrain_Adaptability.png"))
    print(f"[ecdf_phase_space] wrote FigA/FigB/FigC to {args.output_dir}")


if __name__ == "__main__":
    main()
